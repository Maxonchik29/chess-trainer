def theme_text(theme):

    return THEME_EXPLANATIONS.get(
        theme,
        THEME_EXPLANATIONS["Не определено"]
    )

def explain_by_loss(loss, theme=None, best_move=None):

    if loss < 200:

        intro = (
            "🟡 Неточность.\n\n"
            "Этот ход немного ухудшает вашу позицию. "
            "Преимущество ещё сохраняется, но соперник получает более удобную игру."
        )

    elif loss < 500:

        intro = (
            "🟠 Ошибка.\n\n"
            "После этого хода позиция становится заметно хуже. "
            "Соперник получает возможность захватить инициативу."
        )

    else:

        intro = (
            "🔴 Грубая ошибка.\n\n"
            "Этот ход резко ухудшает позицию. "
            "Чаще всего такие ошибки приводят к проигрышу материала или решающей атаке."
        )

    text = intro
    
    if theme not in ("Вилка", "Связка"):
        text += "\n\n"
        text += theme_text(theme)

    if best_move:

        text += f"\n\nЛучшим продолжением было сыграть {best_move}."

    text += (
        "\n\nСовет: перед каждым ходом проверяйте угрозы соперника, "
        "ищите тактические мотивы и только затем принимайте решение."
    )

    return text